"""Where the bridge is, who we are to it, and every request that reaches it.

Configuration comes from the environment:
  DAEDALUS_URL    bridge base URL (default: http://127.0.0.1:8081)
  DAEDALUS_TOKEN  bridge token, as generated by the extension on install
  DAEDALUS_TOKEN_OVERRIDE  one-off override for DAEDALUS_TOKEN
  DAEDALUS_ID     target tab id (optional — omit to send with no tab,
                  which runs in the browser's active tab)

An embedding application may instead put a module named `_settings` on
sys.path exposing `setting(name, default)` and `required(name)`; when one is
importable it takes over configuration lookup, so a deployment can serve these
values from its own store rather than the process environment. Nothing here
depends on that: with no such module the environment is the only source.
"""
import argparse
import functools
import http.client
import json
import os
import sys
import time
import urllib.error
import urllib.parse
import urllib.request


try:
    # Optional embedding hook: an application may put a `_settings` module on
    # sys.path to serve configuration from its own store. It is absent by
    # design in a plain install, which is exactly what the except covers.
    from _settings import (  # pyright: ignore[reportMissingImports]
        setting, required)
except ImportError:                       # bundle not installed — env only
    def setting(name, default=None):
        return os.environ.get(name) or default

    def required(name, hint=''):
        v = os.environ.get(name)
        if not v:
            raise SystemExit(f"{name} is not set (export it)")
        return v

URL = setting('DAEDALUS_URL', 'http://127.0.0.1:8081')


def token():
    # DAEDALUS_TOKEN_OVERRIDE is the one-off override; the durable token
    # DAEDALUS_TOKEN goes through `required` so _settings can serve it
    # from a store instead. Resolving it here rather than at import time is
    # what lets a shell, a scheduled job and a long-lived session all work
    # the same way.
    return (os.environ.get('DAEDALUS_TOKEN_OVERRIDE')
            or os.environ.get('TOKEN') or required('DAEDALUS_TOKEN'))


def tab():
    return os.environ.get('DAEDALUS_ID') or os.environ.get('ID') or ''


NET_CAPTURE_MAX = 20000


def capture_limit(value):
    """argparse type for --max: a capture buffer is a memory budget.

    It lives in the service worker and grows to hold headers and response
    bodies, so a nonpositive value produced a buffer that evicts its only
    event and an enormous one produced no bound at all. The ceiling matches
    NET_CAPTURE_MAX in extension/background.js, which enforces it again on
    arrival — a caller is not the only thing that can send this field.
    """
    try:
        limit = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f'--max must be an integer from 1 to {NET_CAPTURE_MAX}; '
            f'got {value!r}') from None
    if limit < 1 or limit > NET_CAPTURE_MAX:
        raise argparse.ArgumentTypeError(
            f'--max must be an integer from 1 to {NET_CAPTURE_MAX}; '
            f'got {limit}')
    return limit


def positive_timeout(value):
    """argparse type for a result wait.

    A negative wait is worse than a rejected one: the command is PUT to the
    bridge first and the deadline is only checked afterwards, so the poll
    loop runs zero times, the caller is told it timed out, and the browser
    goes on to execute the command anyway. Retrying after that report runs
    the side effect twice. Rejecting the value at parse time means nothing
    has been admitted yet.

    Zero is accepted and keeps the meaning it already has at every call
    site: `args.timeout or <default>` reads it as "unset".
    """
    try:
        seconds = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f'timeout must be a whole number of seconds; '
            f'got {value!r}') from None
    if seconds < 0:
        raise argparse.ArgumentTypeError(
            f'timeout must not be negative; got {seconds}')
    return seconds


def positive_count(value):
    """argparse type for the number of tail entries to display.

    The display slices with `[-n:]`, where n = 0 is the whole buffer and a
    negative n a longer tail than the one asked for.
    """
    try:
        count = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f'count must be a whole number; got {value!r}') from None
    if count < 1:
        raise argparse.ArgumentTypeError(
            f'count must be at least 1; got {count}')
    return count


def quality_limit(value):
    """argparse type for a JPEG quality.

    The worker reads `quality || 80`, so an admitted 0 silently captured at
    the default instead of refusing, and anything past 100 reached Chrome's
    capture call unvalidated.
    """
    try:
        quality = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f'quality must be a whole number; got {value!r}') from None
    if quality < 1 or quality > 100:
        raise argparse.ArgumentTypeError(
            f'quality must be from 1 to 100; got {quality}')
    return quality


def chrome_tab_id(value):
    """A Chrome tab id: the integer Chrome numbers its tabs with.

    The handlers converted the string with bare int() after the command was
    shaped, so `--chrome-tab abc` died with a ValueError traceback instead
    of argparse's refusal before anything is sent.
    """
    try:
        return int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f'{value!r} is not an integer') from None


def expiration_timestamp(value):
    """A cookie expiry: float()'s whole domain, inf and nan included.

    The point is to move the crash to argparse, not to tighten what a shell
    one-liner may pass a cookie.
    """
    try:
        return float(value)
    except ValueError:
        raise argparse.ArgumentTypeError(
            f'{value!r} is not a number') from None


def json_params(value):
    """CDP --params: json.loads()'s whole domain, not only JSON objects.

    A non-object value (`[1,2]`, `3`) is what the operator typed and travels
    as it parsed; only a body json.loads() itself refuses is refused.
    """
    try:
        return json.loads(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError(
            f'{value!r} is not valid JSON: {error}') from None


def _query_path(path, params):
    """Build one bridge path with every query value percent-encoded."""
    query = urllib.parse.urlencode(params)
    return f'{path}?{query}' if query else path


def _http_error_detail(e):
    """The body of a failed response, JSON-decoded when it is JSON.

    An HTTPError body can only be read once. Reading it inside the JSON
    attempt and again in the fallback left the fallback with an empty
    string, so a front end answering with a plain-text page was reported as
    a status and nothing else.
    """
    raw = e.read()
    try:
        return json.loads(raw)
    except Exception:
        return raw.decode(errors='replace')


class ConnectionFailed(Exception):
    """No complete answer: refused, reset, timed out, or cut off mid-body.

    Every api* function turns this into `sys.exit('Connection failed: ...')`.
    It exists as an exception so the one caller that can do better than
    exit — the result wait, whose command is already queued and running —
    can catch it and keep polling.
    """


class ErrorStatus(Exception):
    """A complete answer with an error status; str() is `HTTP <code>: ...`.

    An exception rather than an exit for the same reason as
    ConnectionFailed: the result wait outlives it.
    """


def _failure_report(failure):
    """The words every api* function exits with for a failed request."""
    if isinstance(failure, ErrorStatus):
        return str(failure)
    failed = failure.args[0] if failure.args else failure
    if isinstance(failed, str):  # a wrapper's text: name the wrapper
        failed = failure.__cause__ or failure
    return f'Connection failed: {str(failure) or type(failed).__name__}'


def _json_body(response):
    """Decode a 200's body, refusing one not JSON or too deep as broken.

    An HTML page where the bridge's JSON should be is the front end's
    answer, not the bridge's — the same class of failure as a refused
    connection, and it exits like one.
    """
    try:
        return json.loads(response.read())
    except ValueError as error:
        raise ConnectionFailed(error) from error
    except RecursionError as error:
        raise ConnectionFailed(
            'the answer nests too deep to decode') from error


_MAX_INTERIM_RESPONSES = 100


class _InterimSkippingResponse(http.client.HTTPResponse):
    """An HTTPResponse that also skips the 1xx other than `100 Continue`.

    http.client takes a `103 Early Hints` from a front end for the answer,
    so the real one that follows was never read. `101 Switching Protocols`
    stays final: what follows it is not HTTP.
    """

    def begin(self, **kwargs):
        super().begin(**kwargs)
        skipped = 0
        while (100 <= self.status < 200
               and self.status != http.HTTPStatus.SWITCHING_PROTOCOLS):
            if skipped == _MAX_INTERIM_RESPONSES:
                raise http.client.HTTPException(
                    f'got more than {_MAX_INTERIM_RESPONSES} '
                    'interim responses')
            skipped += 1
            # begin() returns at once while headers is set
            self.headers = None  # pyright: ignore[reportAttributeAccessIssue]
            super().begin(**kwargs)


def _interim_skipping(connection_class):
    return type(connection_class.__name__, (connection_class,),
                {'response_class': _InterimSkippingResponse})


class _HttpHandler(urllib.request.HTTPHandler):
    def do_open(self, http_class, req, **http_conn_args):
        return super().do_open(
            _interim_skipping(http_class), req, **http_conn_args)


class _HttpsHandler(urllib.request.HTTPSHandler):
    def do_open(self, http_class, req, **http_conn_args):
        return super().do_open(
            _interim_skipping(http_class), req, **http_conn_args)


@functools.cache
def _opener():
    """One opener per process, built on first use: the HTTPS handler builds
    an SSL context, which costs milliseconds per request if rebuilt."""
    return urllib.request.build_opener(_HttpHandler, _HttpsHandler)


def _open(req, timeout):
    """urlopen() with interim responses skipped, and no global opener."""
    return _opener().open(req, timeout=timeout)


def _exchange(req, timeout, read):
    """Send one request and return read(response).

    HTTPError and URLError are raised by _open itself. A reset, a
    timeout or an IncompleteRead raised while the body is being READ —
    after _open returned — must be caught here too: those come from the
    proxy in front of the bridge, not from the bridge, and they are the
    same class of failure as a refused connection, no answer arrived.
    HTTPError is a URLError and URLError is an OSError, so the order of
    the clauses is the order of specificity.
    """
    try:
        with _open(req, timeout) as r:
            return read(r)
    except urllib.error.HTTPError as e:
        try:
            detail = _http_error_detail(e)
        except (OSError, http.client.HTTPException) as failure:
            raise ConnectionFailed(failure) from failure
        raise ErrorStatus(f'HTTP {e.code}: {detail}') from e
    except urllib.error.URLError as e:
        raise ConnectionFailed(e.reason) from e
    except (OSError, http.client.HTTPException) as e:
        raise ConnectionFailed(e) from e


def _exchange_or_exit(req, timeout, read):
    try:
        return _exchange(req, timeout, read)
    except (ConnectionFailed, ErrorStatus) as e:
        sys.exit(_failure_report(e))


def _request(method, path, body=None, timeout=30, headers=None):
    """api() that raises ConnectionFailed or ErrorStatus, never exiting."""
    url = URL + path
    data = json.dumps(body).encode() if body else None
    # The bridge decides credentials before it reads a body, so the token goes
    # in a header too. Without it a request larger than the bridge's
    # unauthenticated window is refused before its body is read at all. It is
    # also what keeps a reusable credential out of the request target, where
    # every proxy access log would keep it.
    headers = dict(headers or {}, **{'Authorization': f'Bearer {token()}'})
    if data:
        headers['Content-Type'] = 'application/json'
    req = urllib.request.Request(
        url, data=data, headers=headers, method=method)
    return _exchange(req, timeout, _json_body)


def api(method, path, body=None, timeout=30, headers=None):
    try:
        return _request(method, path, body, timeout, headers)
    except (ConnectionFailed, ErrorStatus) as e:
        sys.exit(_failure_report(e))


def api_raw(method, path):
    """Like api() but returns raw bytes instead of JSON."""
    url = URL + path
    req = urllib.request.Request(
        url, method=method, headers={'Authorization': f'Bearer {token()}'})
    return _exchange_or_exit(req, 30, lambda r: r.read())


def api_delete(path, body):
    """Send DELETE request with JSON body."""
    url = URL + path
    data = json.dumps(body).encode()
    req = urllib.request.Request(
        url, data=data, method='DELETE',
        headers={'Content-Type': 'application/json',
                 'Authorization': f'Bearer {token()}'})
    return _exchange_or_exit(req, 30, _json_body)


def _result_answer(path, **timeout):
    """A /result JSON object; ConnectionFailed if a 2xx body is not one."""
    answer = _request('GET', path, **timeout)
    if not isinstance(answer, dict):
        raise ConnectionFailed('the answer is JSON but not an object')
    return answer


def wait_for_result(cmd_id, target_tab, delivery_id, timeout, interval=0.5):
    """Return the result for one command delivery, or None on timeout.

    A timeout after any failed result request, except a peek timeout landing
    at the deadline, exits instead, naming the outcome unknown: a failed
    consume may have claimed the result, so no later pending answer can say
    the command did not run.

    The PUT response's delivery id distinguishes this invocation from a stale
    result with the same command id. Conditional consume names the generation
    just peeked, so a newer result that replaces it remains for its owner.

    The wait ramps 20ms -> `interval` instead of sleeping `interval` up front:
    most commands finish in tens of milliseconds, and the fixed first sleep
    charged half a second of dead time to every command that waited, however
    fast the result actually landed. The ramp keeps a slot that stays pending
    from becoming a request flood, which is what a flat short interval would
    be. Same shape as the MCP poller, for the same reason.
    """
    params = {}
    if target_tab:
        params['tab'] = target_tab
    if delivery_id:
        params['delivery'] = delivery_id
    # One monotonic deadline for the whole wait, and every blocking step is
    # capped by what is left of it, so a single stalled poll cannot run past
    # the timeout the caller asked for. Wall-clock time.time() also went
    # backwards under an NTP step; monotonic does not.
    deadline = time.monotonic() + timeout
    wait = 0.02
    failure = None
    while True:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        time.sleep(min(wait, remaining))
        wait = min(wait * 2, interval)
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            break
        try:
            res = _result_answer(_query_path('/result', params),
                                 timeout=remaining)
        except (ConnectionFailed, ErrorStatus) as error:
            # The bridge answers /result at once, so a failed peek is the
            # proxy's, and the queued command still runs: wait on as if
            # pending. A timeout once the deadline has passed is that
            # deadline, each peek being handed what is left.
            if not (isinstance(error.args[0], TimeoutError)
                    and time.monotonic() >= deadline):
                failure = error
            continue
        if res.get('pending'):
            continue
        result_delivery_id = res.get('deliveryId')
        if (res.get('id') != cmd_id
                or not delivery_id
                or not result_delivery_id
                or result_delivery_id != delivery_id):
            continue  # another caller's result — leave it in place for them
        generation = res.get('resultGeneration')
        if not generation:
            continue
        # The consume is what actually claims the result, so it is allowed to
        # finish: giving up here would leave a result nobody takes. It is
        # still bounded, by the ordinary request timeout. A failed one is not
        # final while time is left: the next lap peeks and consumes again.
        try:
            consumed = _result_answer(_query_path('/result', {
                **params, 'consume': '1', 'expected': generation}))
        except (ConnectionFailed, ErrorStatus) as error:
            failure = error
            continue
        if (consumed.get('consumed') is not True
                or consumed.get('resultGeneration') != generation):
            continue
        return res
    if failure is not None:
        sys.exit(f'Timeout ({timeout}s), outcome unknown: a result request '
                 f'failed ({_failure_report(failure)}). The command was sent '
                 'and may have run; check its effect before retrying.')
    return None
