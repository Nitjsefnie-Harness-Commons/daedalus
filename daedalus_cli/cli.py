def do_segment_job(args):
    # Minting is idempotent for the owning token, so this both creates a job
    # and re-fetches its capability. The printed sig substitutes for __SIG__
    # in examples/hls-segment-relay.js; it authorizes segment writes to this
    # one job only, which is why the relay script never needs the bridge token.
    res = api('POST', '/segment-job', {'token': token(), 'job': args.job})
    print(res['sig'])


def do_segment_status(args):
    # /segment-status takes the job-scoped capability, not the bridge token.
    # The capability is only handed out by POST /segment-job, which MINTS the
    # job when it does not exist yet (idempotent for the owning token) — so a
    # status query for a mistyped name creates that job as a side effect.
    req = urllib.request.Request(
        f'{URL}/segment-job',
        data=json.dumps({'token': token(), 'job': args.job}).encode(),
        headers={'Content-Type': 'application/json'}, method='POST')
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            sig = json.loads(r.read())['sig']
    except urllib.error.HTTPError as e:
        if e.code == 409:
            sys.exit(f'segment-status: job "{args.job}" is owned by a different token')
        try:
            err = json.loads(e.read())
        except Exception:
            err = e.read().decode()
        sys.exit(f'HTTP {e.code}: {err}')
    except urllib.error.URLError as e:
        sys.exit(f'Connection failed: {e.reason}')
    res = api('GET', _query_path(
        '/segment-status', {'job': args.job, 'sig': sig}))
    count = res.get('count', 0)
    done = res.get('done', [])
    print(f'Job: {args.job}  Segments: {count}')
    if done:
        full = set(range(min(done), max(done) + 1))
        gaps = sorted(full - set(done))
        if gaps:
            print(f'Gaps ({len(gaps)}): {gaps[:30]}{"..." if len(gaps) > 30 else ""}')
        else:
            print(f'Complete: {min(done)}–{max(done)}')


# ─── Extension command helper ───

def ext_cmd(cmd_id, cmd_type, timeout=10, **fields):
    """Send an extension command and wait for result. Returns result dict or exits on error."""
    cmd = {'id': cmd_id, 'type': cmd_type, 'token': token(), 'tab': 'extension', **fields}
    sent = api('PUT', '/command', cmd)
    res = wait_for_result(cmd_id, 'extension', sent.get('did'), timeout)
    if res is None:
        sys.exit(f'Timeout ({timeout}s)')
    if res.get('error'):
        sys.exit(f'Error: {res["error"]}')
    return res.get('result', {})


