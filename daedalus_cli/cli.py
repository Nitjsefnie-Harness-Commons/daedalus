#!/usr/bin/env python3
"""Daedalus bridge CLI — drive the browser extension from a shell.

Configuration comes from the environment:
  DAEDALUS_URL    bridge base URL (default: http://127.0.0.1:8081)
  DAEDALUS_TOKEN  bridge token, as generated by the extension on install
  TOKEN           one-off override for DAEDALUS_TOKEN
  ID              target tab id (optional — omit to broadcast to every tab)

An embedding application may instead put a module named `_settings` on
sys.path exposing `setting(name, default)` and `required(name)`; when one is
importable it takes over configuration lookup, so a deployment can serve these
values from its own store rather than the process environment. Nothing here
depends on that: with no such module the environment is the only source.
"""
import argparse, json, os, sys, time, urllib.request, urllib.error, urllib.parse

from . import __version__

try:
    # Optional embedding hook: an application may put a `_settings` module on
    # sys.path to serve configuration from its own store. It is absent by
    # design in a plain install, which is exactly what the except covers.
    from _settings import setting, required  # pyright: ignore[reportMissingImports]
except ImportError:                       # bundle not installed — env only
    def setting(name, default=None):
        return os.environ.get(name) or default

    def required(name, hint=''):
        v = os.environ.get(name)
        if not v:
            raise SystemExit(f"{name} is not set (export it)")
        return v

URL = setting('DAEDALUS_URL', 'http://127.0.0.1:8081')


def token():
    # TOKEN is the one-off override; DAEDALUS_TOKEN is the durable one, and it
    # goes through `required` so an embedding _settings module can serve it from
    # a store instead. Resolving it here rather than at import time is what lets
    # a shell, a scheduled job and a long-lived session all work the same way.
    return os.environ.get('TOKEN') or required('DAEDALUS_TOKEN')


def tab():
    return os.environ.get('ID', '')


# ─── HTTP helpers ───

def _query_path(path, params):
    """Build one bridge path with every query value percent-encoded."""
    query = urllib.parse.urlencode(params)
    return f'{path}?{query}' if query else path


def api(method, path, body=None):
    url = URL + path
    data = json.dumps(body).encode() if body else None
    headers = {'Content-Type': 'application/json'} if data else {}
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        try:
            err = json.loads(e.read())
        except Exception:
            err = e.read().decode()
        sys.exit(f'HTTP {e.code}: {err}')
    except urllib.error.URLError as e:
        sys.exit(f'Connection failed: {e.reason}')


def api_raw(method, path):
    """Like api() but returns raw bytes instead of JSON."""
    url = URL + path
    req = urllib.request.Request(url, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.read()
    except urllib.error.HTTPError as e:
        sys.exit(f'HTTP {e.code}')
    except urllib.error.URLError as e:
        sys.exit(f'Connection failed: {e.reason}')


def api_delete(path, body):
    """Send DELETE request with JSON body."""
    url = URL + path
    data = json.dumps(body).encode()
    req = urllib.request.Request(url, data=data, headers={'Content-Type': 'application/json'}, method='DELETE')
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        try:
            err = json.loads(e.read())
        except Exception:
            err = e.read().decode()
        sys.exit(f'HTTP {e.code}: {err}')
    except urllib.error.URLError as e:
        sys.exit(f'Connection failed: {e.reason}')


def wait_for_result(cmd_id, target_tab, delivery_id, timeout, interval=0.5):
    """Return the result for one command delivery, or None on timeout.

    The PUT response's delivery id distinguishes this invocation from a stale
    result with the same command id. Conditional consume names the generation
    just peeked, so a newer result that replaces it remains for its owner.
    """
    params = {'token': token()}
    if target_tab:
        params['tab'] = target_tab
    t0 = time.time()
    while time.time() - t0 < timeout:
        time.sleep(interval)
        res = api('GET', _query_path('/result', params))
        if res.get('pending'):
            continue
        if (res.get('id') != cmd_id
                or res.get('deliveryId') != delivery_id):
            continue  # another caller's result — leave it in place for them
        generation = res.get('resultGeneration')
        if not generation:
            continue
        consumed = api('GET', _query_path('/result', {
            **params, 'consume': '1', 'expected': generation}))
        if (consumed.get('consumed') is not True
                or consumed.get('resultGeneration') != generation):
            continue
        return res
    return None


# ─── Result display ───

def validate_result(res):
    """Check result JSON has expected fields, warn on missing."""
    expected = {'id', 'result', 'error', 'ts', 'token'}
    missing = expected - set(res.keys())
    if missing:
        print(f'⚠ Missing fields: {", ".join(sorted(missing))}', file=sys.stderr)
    if 'id' in res and not isinstance(res['id'], str):
        print(f'⚠ id is {type(res["id"]).__name__}, expected str', file=sys.stderr)


def _format_eval_world(world):
    """Present the wire `world` value only as an execution channel."""
    return f'channel={world}'


def print_result(res, raw=False):
    if raw:
        print(json.dumps(res, indent=2, ensure_ascii=False))
        return

    validate_result(res)

    hdr = f'← {res.get("id", "?")}'
    t = res.get('tabId', '')
    world = res.get('world', '')
    ms = res.get('exec_ms')
    if t:
        hdr += f'  tab={t[:12]}'
    if world:
        hdr += f'  @{_format_eval_world(world)}'
    if isinstance(ms, (int, float)):
        hdr += f'  {ms}ms'

    err = res.get('error')
    if err:
        print(f'{hdr}  ERROR: {err}')
        sys.exit(1)

    print(hdr)
    r = res.get('result')
    if isinstance(r, (dict, list)):
        print(json.dumps(r, indent=2, ensure_ascii=False))
    elif r is not None:
        print(r)
    else:
        print('(undefined)')


# ─── Command dispatch core ───

def send_and_wait(cmd_id, code, target_tab, wait, timeout):
    if not cmd_id:
        sys.exit('Command ID is required')
    if not code:
        sys.exit('Code is empty')
    if not isinstance(cmd_id, str):
        sys.exit(f'Command ID must be a string, got {type(cmd_id).__name__}')

    payload = {'token': token(), 'id': cmd_id, 'code': code}
    if target_tab:
        payload['tab'] = target_tab

    resp = api('PUT', '/command', payload)
    target = resp.get('target', '?')
    print(f'→ {cmd_id} → {target}  ({len(code)} bytes)')

    if not wait:
        return

    res = wait_for_result(cmd_id, target_tab, resp.get('did'), timeout)
    if res is None:
        sys.exit(f'Timeout ({timeout}s) — no result received')
    print_result(res)


# ─── Subcommands ───

def do_tabs(args):
    tabs = api('GET', _query_path('/tabs', {'token': token()}))
    if getattr(args, 'json', False):
        print(json.dumps(tabs or [], indent=2))
        return
    if not tabs:
        print('No active tabs')
        return
    for t in sorted(tabs, key=lambda x: x.get('age', 0)):
        tid = t['tabId']
        age = t.get('age', '?')
        url = t.get('url', '')
        title = t.get('title', '')[:50]
        print(f'  {tid}  {age:>4}s  {title:<50}  {url}')


def do_put(args):
    if args.file == '-':
        code = sys.stdin.read()
    else:
        if not os.path.isfile(args.file):
            sys.exit(f'File not found: {args.file}')
        with open(args.file, encoding='utf-8') as f:
            code = f.read()
    target_tab = '' if args.broadcast else tab()
    send_and_wait(args.id, code.strip(), target_tab,
                  wait=not args.no_result, timeout=args.timeout)


def do_exec(args):
    target_tab = '' if args.broadcast else tab()
    send_and_wait(args.id, args.code.strip(), target_tab,
                  wait=not args.no_result, timeout=args.timeout)


def do_result(args):
    params = {'token': token()}
    t = tab()
    if t:
        params['tab'] = t
    if args.consume:
        params['consume'] = '1'
    res = api('GET', _query_path('/result', params))
    if res.get('pending'):
        print('No result pending')
        return
    print_result(res, raw=args.raw)


def do_ping(args):
    target_tab = tab()
    t0 = time.time()
    payload = {'token': token(), 'id': '_ping', 'code': 'document.title'}
    if target_tab:
        payload['tab'] = target_tab
    sent = api('PUT', '/command', payload)

    res = wait_for_result(
        '_ping', target_tab, sent.get('did'), 10, interval=0.3)
    if res is None:
        sys.exit('Ping timeout (10s)')
    err = res.get('error')
    if err:
        sys.exit(f'Ping error: {err}')
    ms = (time.time() - t0) * 1000
    title = res.get('result', '')
    world = res.get('world', '')
    loc = f'@{_format_eval_world(world)}' if world else ''
    print(f'Pong {loc}: "{title}"  ({ms:.0f}ms)')


