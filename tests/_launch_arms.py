"""Every guard arm in the two launch-audit analysers, and its state.

A guard arm with no row that fails when it is deleted is UNDRIVEN:
deleting it leaves the suite green, and the change it makes to a real
source file is invisible to CI. So every arm here is in exactly one of
three states, and no fourth:

CONTROLLED - a row, or a control in ARM_CONTROLS below, that fails when
the arm is deleted. `evidence` names it.
REDUNDANT - the arm cannot change any verdict because a named other arm
or bound already decides. `evidence` names that bound.
DEAD - no input reaches it, and `evidence` is the argument why.

"Live and deliberately unpinned" is not a fourth state; it was withdrawn.
Every arm in this list was classified by DELETING it from the real
analyser in a worktree and re-asking every row and every probe shape,
not by reading it. The arms the two row files could not express are the
three in ARM_CONTROLS, which assert sites AND refusals rather than the
one-refusal shape a LAUNCH_REFUSAL_ROW is built for, and the two the
step ceiling names, whose mutants do not answer wrong but do not
stop, so there is no verdict for a row to hold.

`line` is where the arm was classified, `cut` is the one clause the
sweep deleted (`op:line[:arg]`, which `tests/_arm_sweep.py` replays),
and `anchor` is the text of the arm's own block, so a reader can find it
and a test can notice it moving.
"""
